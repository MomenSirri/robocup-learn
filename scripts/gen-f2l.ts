/**
 * Generates all 41 F2L cases (front-right slot) with short, trigger-built
 * algorithms. Each case is a class of corner+edge placements up to U turns.
 * Dijkstra over the 150 possible pair placements, where an edge is
 * "optional U turn + one trigger" (each trigger only touches the FR pair and
 * the top layer), finds the cheapest trigger sequence for every class.
 *
 * Run: npx tsx scripts/gen-f2l.ts > src/content/f2l.generated.ts
 */
import { solvedState, applyAlg, parseAlg, invertAlg, algToString, relPos, stickerDir, CubeState, Move } from '../src/cube/cube';
import { simplify, f2lFeatures } from '../src/cube/analysis';

const TRIGGERS = ["R U R'", "R U' R'", "R U2 R'", "F' U F", "F' U' F", "F' U2 F", "R' F R F'", "F R' F' R"];
const PRE = ['', 'U', "U'", 'U2'];
const MACROS: { text: string; moves: Move[]; cost: number }[] = [];
for (const p of PRE)
  for (const t of TRIGGERS) {
    const text = (p + ' ' + t).trim();
    const moves = parseAlg(text);
    MACROS.push({ text, moves, cost: moves.length + 0.15 * moves.filter((m) => m.base === 'F').length });
  }
for (const p of PRE.slice(1)) MACROS.push({ text: p, moves: parseAlg(p), cost: 1 });

const key = (s: CubeState) =>
  [relPos(s, 'DFR'), stickerDir(s, 'DFR', 'D'), stickerDir(s, 'DFR', 'F'), relPos(s, 'FR'), stickerDir(s, 'FR', 'F')].map((v) => v.join(',')).join('|');
const U = parseAlg('U');
function classKey(s: CubeState) {
  let best = '';
  let t = s;
  for (let k = 0; k < 4; k++) {
    const kk = key(t);
    if (!best || kk < best) best = kk;
    t = applyAlg(t, U);
  }
  return best;
}

// Dijkstra over exact pair placements
const dist = new Map<string, { cost: number; seq: string[]; state: CubeState }>();
const start = solvedState();
dist.set(key(start), { cost: 0, seq: [], state: start });
const done = new Set<string>();
for (;;) {
  let bestK: string | null = null;
  for (const [k, v] of dist) if (!done.has(k) && (bestK === null || v.cost < dist.get(bestK)!.cost)) bestK = k;
  if (bestK === null) break;
  done.add(bestK);
  const cur = dist.get(bestK)!;
  for (const m of MACROS) {
    const ns = applyAlg(cur.state, m.moves);
    const nk = key(ns);
    const c = cur.cost + m.cost;
    const old = dist.get(nk);
    if (!old || c < old.cost - 1e-9) dist.set(nk, { cost: c, seq: [...cur.seq, m.text], state: ns });
  }
}

// best per class; the solving algorithm is the inverse of the setup sequence
const classes = new Map<string, { cost: number; alg: string }>();
for (const [, v] of dist) {
  if (v.seq.length === 0) continue;
  const ck = classKey(v.state);
  if (ck === classKey(start)) continue;
  const alg = algToString(simplify(invertAlg(parseAlg(v.seq.join(' ')))));
  const old = classes.get(ck);
  if (!old || v.cost < old.cost) classes.set(ck, { cost: v.cost, alg });
}

const rows = [...classes.values()].map((c) => {
  const s = applyAlg(solvedState(), invertAlg(parseAlg(c.alg)));
  return { alg: c.alg, f: f2lFeatures(s) };
});
console.error('classes:', rows.length);
console.log('// Generated by scripts/gen-f2l.ts — do not edit by hand.');
console.log('export const F2L_ALGS: string[] = [');
for (const r of rows) console.log(`  ${JSON.stringify(r.alg)},`);
console.log('];');
